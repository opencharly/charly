// invokeConfigSetup handles sdk.OpConfigSetup: req.ParamsJson is a #PodConfigSetupRequest.
func invokeConfigSetup(ctx context.Context, req *pb.InvokeRequest) (*pb.InvokeReply, error) {
	ex, err := sdk.ExecutorFromInvoke(req.GetExecutorBrokerId())
	if err != nil {
		return nil, fmt.Errorf("plugin-deploy-pod config-setup: executor: %w", err)
	}
	var r spec.PodConfigSetupRequest
	if err := json.Unmarshal(req.GetParamsJson(), &r); err != nil {
		return nil, fmt.Errorf("plugin-deploy-pod config-setup: decode request: %w", err)
	}
	if r.ListSidecars {
		var rep spec.PodConfigListSidecarsReply
		if err := hostBuild(ctx, ex, podConfigListSidecarsKind, spec.PodConfigLoadDeployRequest{}, &rep); err != nil {
			return nil, err
		}
		names := append([]string{}, rep.Names...)
		sort.Strings(names)
		for _, name := range names {
			fmt.Printf("%-20s %s\n", name, rep.Descriptions[name])
		}
		return marshalReply(spec.PodConfigSetupReply{})
	}
	if err := runPodConfigSetup(ctx, ex, &r); err != nil {
		return nil, err
	}
	return marshalReply(spec.PodConfigSetupReply{})
}

// hostBuild is the generic seam-call helper: marshal req, call HostBuild(kind), unmarshal into
// rep. Every "pod-config-*" seam follows this shape.
func hostBuild(ctx context.Context, ex *sdk.Executor, kind string, req, rep any) error {
	reqJSON, err := json.Marshal(req)
	if err != nil {
		return err
	}
	resJSON, err := ex.HostBuild(ctx, kind, reqJSON)
	if err != nil {
		return err
	}
	if rep == nil || len(resJSON) == 0 {
		return nil
	}
	return json.Unmarshal(resJSON, rep)
}

func runPodConfigSetup(ctx context.Context, ex *sdk.Executor, c *spec.PodConfigSetupRequest) error {
	rt, err := kit.ResolveRuntime()
	if err != nil {
		return err
	}
	switch rt.RunMode {
	case "quadlet", "direct":
	default:
		return fmt.Errorf("charly config requires run_mode=quadlet or direct (current: %s)", rt.RunMode)
	}
	if c.Box == "" {
		return fmt.Errorf("image name is required")
	}
	if spec.IsRemoteImageRef(kit.StripURLScheme(c.Box)) {
		return fmt.Errorf("remote refs are not accepted here; run 'charly box pull %s' first, then 'charly config <image-name>'", c.Box)
	}
	c.Box, c.Instance = deploykit.CanonicalizeDeployArg(c.Box, c.Instance)
	if err := deploykit.RejectImageRefAsDeployName(c.Box); err != nil {
		return err
	}
	return runConfig(ctx, ex, rt, c)
}

